function [tx, rx] = plutoRadios(cfg)
% PLUTORADIOS  Create the Pluto transmitter and receiver System objects.
% One Pluto is used for both: TX1 antenna -> over the air -> RX1 antenna
% (antennas about 2 cm apart; this is the setup that produced the results).
% Returns empty objects in simulation mode.

if cfg.simulate
    tx = []; rx = [];
    return;
end

tx = sdrtx('Pluto', ...
    'RadioID',            cfg.radioID, ...
    'CenterFrequency',    cfg.fc, ...
    'BasebandSampleRate', cfg.fs, ...
    'Gain',               cfg.txGain);

rx = sdrrx('Pluto', ...
    'RadioID',            cfg.radioID, ...
    'CenterFrequency',    cfg.fc, ...
    'BasebandSampleRate', cfg.fs, ...
    'SamplesPerFrame',    cfg.samplesPerFrame, ...
    'OutputDataType',     'double', ...
    'GainSource',         cfg.rxGainMode);
if strcmp(cfg.rxGainMode, 'Manual')
    rx.Gain = cfg.rxGain;
end
end
